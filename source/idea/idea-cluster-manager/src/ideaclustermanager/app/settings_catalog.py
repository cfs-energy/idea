def settings_catalog(storage_names=None, backup_rules=None):
    """Expand reviewed storage fields for existing attachments, never accept arbitrary keys."""
    result = [
        item
        for item in CATALOG
        if storage_names is None
        or item['module'] != 'shared-storage'
        or item['path'].split('.')[0] in storage_names
    ]
    templates = [
        item for item in CATALOG if item['key'].startswith('shared-storage.data.')
    ]
    for name in sorted(set(storage_names or ()) - {'apps', 'data'}):
        if not re.fullmatch(r'[A-Za-z0-9_-]+', name):
            continue
        for template in templates:
            item = deepcopy(template)
            item['key'] = item['key'].replace(
                'shared-storage.data.', f'shared-storage.{name}.', 1
            )
            item['path'] = item['path'].replace('data.', f'{name}.', 1)
            item['section'] = item['section'].replace('Data', _words(name), 1)
            result.append(item)
    for prefix, names in (backup_rules or {}).items():
        templates = [
            item for item in CATALOG if item['key'].startswith(f'{prefix}.default.')
        ]
        for name in sorted(set(names) - {'default'}):
            if not re.fullmatch(r'[A-Za-z0-9_-]+', name):
                continue
            for template in templates:
                item = deepcopy(template)
                item['key'] = item['key'].replace(
                    '.rules.default.', f'.rules.{name}.', 1
                )
                item['path'] = item['path'].replace(
                    '.rules.default.', f'.rules.{name}.', 1
                )
                item['section'] = item['section'].replace('Default', _words(name))
                result.append(item)
    return result


def coerce_value(setting, value):
    """Validate a JSON value and return the native scalar/list used by config set."""
    kind, rule = setting['value_type'], setting['validation']
    key = setting['key']

    def invalid(reason):
        raise exceptions.invalid_params(f'{key}: {reason}')

    if value is None:
        if rule['required']:
            invalid('a value is required')
        return None
    if kind in ('string', 'enum', 'secret'):
        if not isinstance(value, str):
            invalid('must be a string')
    elif kind == 'boolean':
        if isinstance(value, str) and value.lower() in (
            'true',
            'yes',
            'y',
            '1',
            'on',
            'false',
            'no',
            'n',
            '0',
            'off',
        ):
            value = value.lower() in ('true', 'yes', 'y', '1', 'on')
        if type(value) is not bool:
            invalid('must be a boolean')
    elif kind == 'integer':
        if isinstance(value, str) and re.fullmatch(r'[+-]?\d+', value):
            value = int(value)
        if type(value) is not int:
            invalid('must be an integer')
    elif kind == 'number':
        if isinstance(value, str):
            try:
                value = float(value)
            except ValueError:
                invalid('must be a finite number')
        if type(value) not in (float, int) or not math.isfinite(value):
            invalid('must be a finite number')
    elif kind == 'list':
        if isinstance(value, str):
            value = [item.strip() for item in value.split(',') if item.strip()]
        if not isinstance(value, list) or any(
            not isinstance(item, str) for item in value
        ):
            invalid('must be a list of strings')
    else:
        invalid('unsupported value type')
    if key == 'directoryservice.ldap_options':
        # The directory reader expects literal dictionaries encoded as strings.
        for option in value:
            try:
                parsed = ast.literal_eval(option)
            except (ValueError, SyntaxError):
                invalid('each option must be a literal dictionary')
            if (
                not isinstance(parsed, dict)
                or type(parsed.get('code')) is not int
                or 'value' not in parsed
            ):
                invalid('each option must include an integer code and a value')
    if rule['required'] and value in ('', []):
        invalid('a value is required')
    if kind in ('integer', 'number'):
        if 'minimum' in rule and value < rule['minimum']:
            invalid(f'must be at least {rule["minimum"]}')
        if 'maximum' in rule and value > rule['maximum']:
            invalid(f'must be at most {rule["maximum"]}')
    if kind == 'enum' and value not in setting['choices']:
        invalid('must be one of: ' + ', '.join(setting['choices']))
    if value and 'pattern' in rule and not re.fullmatch(rule['pattern'], value):
        invalid('does not match the required format')
    return value


def coerce_settings(module, settings, catalog=CATALOG):
    """Validate the entire update before any writes and return values plus effects."""
    definitions = {item['path']: item for item in catalog if item['module'] == module}
    effects = {}

    def visit(values, prefix=''):
        if not isinstance(values, dict):
            raise exceptions.invalid_params('settings must be an object')
        result = {}
        for name, value in values.items():
            if not isinstance(name, str) or any(char in name for char in '.:,'):
                raise exceptions.invalid_params(
                    'setting names must be nested object keys'
                )
            path = f'{prefix}.{name}' if prefix else name
            if path in definitions:
                result[name] = coerce_value(definitions[path], value)
                effects[path] = definitions[path]['effect']
            elif isinstance(value, dict) and value:
                result[name] = visit(value, path)
            else:
                raise exceptions.invalid_params(
                    f'{module}.{path} is not in the settings catalog'
                )
        return result

    return visit(settings), effects
