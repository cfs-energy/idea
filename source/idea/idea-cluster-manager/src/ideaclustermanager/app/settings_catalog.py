def _words(value):
    return value.replace('_', ' ').replace('-', ' ').capitalize()


def _definition(row):
    key, value_type, effect, group, advanced, uncertain = row
    # Mail delivery belongs with notifications, and package/driver knobs are
    # deployment details rather than a frequently used administrator workflow.
    group = {'mail': 'email', 'software': 'deployment'}.get(group, group)
    module, path = key.split('.', 1)
    leaf = path.split('.')[-1]
    section = ' / '.join(_words(part) for part in path.split('.')[:-1]) or 'General'
    label = _words(leaf)
    validation = {'required': False}
    choices = _KEY_CHOICES.get(key, _CHOICES.get(leaf))
    if '.schedule.' in key and leaf == 'type':
        choices = [
            'NO_SCHEDULE',
            'WORKING_HOURS',
            'STOP_ON_IDLE',
            'START_ALL_DAY',
            'CUSTOM_SCHEDULE',
        ]
    if module == 'shared-storage' and leaf == 'provider':
        choices = [
            'efs',
            'fsx_lustre',
            'fsx_netapp_ontap',
            'fsx_openzfs',
            'fsx_windows_file_server',
        ]
    if choices:
        value_type = 'enum'
    if value_type in ('integer', 'number'):
        validation['minimum'] = 0
        if any(word in leaf for word in ('port', 'max_workers', 'volume_size')):
            validation['minimum'] = 1
        if leaf.endswith('port'):
            validation['maximum'] = 65535
        if 'percent' in leaf or leaf in (
            'cpu_utilization_threshold',
            'target_utilization',
        ):
            validation['maximum'] = 100
        if leaf == 'cidr_mask':
            validation.update(minimum=16, maximum=28)
        if leaf in ('running_job_penalty', 'c1', 'c2', 'max_provisioning_retries'):
            validation.pop('minimum', None)
        if leaf == 'max_disable_fraction':
            validation.update(minimum=0, maximum=1)
        if key == 'cluster-manager.accounts.reconcile.interval_minutes':
            validation.update(minimum=1, maximum=1440)
        if leaf == 'sqs_wait_time':
            validation.update(maximum=20)
        if leaf == 'polling_messages_max':
            validation.update(minimum=1, maximum=10)
        if leaf == 'default_log_level':
            validation.update(maximum=5)
        if key == 'scheduler.efa.max_interfaces':
            validation.update(minimum=1, maximum=2)
    if leaf in ('start_up_time', 'shut_down_time'):
        validation['pattern'] = r'^([01][0-9]|2[0-3]):[0-5][0-9]$'
    if value_type == 'secret':
        validation['pattern'] = (
            r'^arn:aws(?:-us-gov|-cn)?:secretsmanager:[a-z0-9-]+:[0-9]{12}:secret:[A-Za-z0-9/_+=.@-]+$'
        )
    if leaf in (
        'sender_email',
        'administrator_email',
        'from_email',
        'reply_to_address',
    ):
        validation['pattern'] = r'^[^\s@]+@[^\s@]+\.[^\s@]+$'
    if key == 'cluster-manager.web_portal.custom_dashboard.url':
        validation['pattern'] = r'^https?://[^\s]+$'
    if leaf in ('mount_dir', 'mount_point'):
        validation['pattern'] = r'^/[^\x00]*$'
    if leaf == 'provider' or key in (
        'cluster-manager.web_portal.title',
        'cluster.timezone',
        'cluster.locale',
    ):
        validation['required'] = True
    description = _DESCRIPTIONS.get(
        key, f'{label} for {section.lower()} in {module.replace("-", " ")}.'
    )
    if value_type == 'secret':
        description = 'Reference to a Secrets Manager secret; the secret value is never stored here.'
    if uncertain:
        description += ' Restart is the conservative classification; no live refresh could be confirmed.'
    return dict(
        key=key,
        module=module,
        path=path,
        group=group,
        section=section,
        label=label,
        description=description,
        value_type=value_type,
        choices=choices or [],
        validation=validation,
        advanced=advanced,
        effect=effect,
    )


